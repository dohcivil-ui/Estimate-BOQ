import { describe, it, expect } from 'vitest';
import { bahtText } from './bahtText';

describe('bahtText', () => {
  it('golden ปร.6 — 13,938,000', () => {
    expect(bahtText(13938000)).toBe('สิบสามล้านเก้าแสนสามหมื่นแปดพันบาทถ้วน');
  });
  it('golden ยอดสุทธิ — 12,506,000', () => {
    expect(bahtText(12506000)).toBe('สิบสองล้านห้าแสนหกพันบาทถ้วน');
  });
  it('ครุภัณฑ์ — 1,432,000', () => {
    expect(bahtText(1432000)).toBe('หนึ่งล้านสี่แสนสามหมื่นสองพันบาทถ้วน');
  });
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [20, 'ยี่สิบบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [100, 'หนึ่งร้อยบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
  ])('อ่านเลข %i → %s', (n, expected) => {
    expect(bahtText(n as number)).toBe(expected as string);
  });
  it('มีสตางค์ — 1,234.50', () => {
    expect(bahtText(1234.5)).toBe('หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์');
  });
  it('สตางค์เอ็ด — 0.21', () => {
    expect(bahtText(0.21)).toBe('ยี่สิบเอ็ดสตางค์');
  });
});
